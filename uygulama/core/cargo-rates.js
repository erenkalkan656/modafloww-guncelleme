/** Bir firmanın desi fiyatı (KDV hariç). 100 desi üstü son iki satırın farkıyla uzatılır. */
function desiPrice(rates, carrier, desi) {
  const r = rates || OFFICIAL_RATES;
  const ci = r.carriers.indexOf(carrier);
  if (ci < 0) return null;
  const rows = Array.isArray(r.rows) ? r.rows : Object.keys(r.rows).sort((a, b) => a - b).map((k) => r.rows[k]);
  const d = Math.max(0, Math.ceil(Number(desi) || 0));
  if (d < rows.length) return rows[d][ci];
  const last = rows[rows.length - 1][ci], prev = rows[rows.length - 2][ci];
  return Math.round((last + (d - (rows.length - 1)) * (last - prev)) * 100) / 100;
}

